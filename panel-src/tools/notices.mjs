// Writes THIRD_PARTY_NOTICES.md: the licence text of everything that reaches the page. build.mjs strips the licence
// comments from the bundle (legalComments: none), so this file is where the notices live (R8 §2 rule 6). It is generated
// from the licence files really installed (node_modules) and vendored (assets/fonts/licenses), so it cannot drift from them.
//
//   node tools/notices.mjs           writes panel-src/THIRD_PARTY_NOTICES.md
//   node tools/notices.mjs --check   fails if the file on disk is not what would be written

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { EXPECTED } from "../check-lock.mjs";
import { FACES, LICENSES_DIR } from "./fonts.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.join(here, "..");
export const NOTICES = path.join(ROOT, "THIRD_PARTY_NOTICES.md");

const lf = (text) => text.replace(/\r\n/g, "\n").replace(/\s+$/, "") + "\n";

function packageLicense(name) {
  const dir = path.join(ROOT, "node_modules", name);
  const file = ["LICENSE", "LICENSE.md", "LICENSE.txt"].map((f) => path.join(dir, f)).find((f) => existsSync(f));
  if (!file) throw new Error(`${name} has no licence file in node_modules (run npm ci --ignore-scripts)`);
  return lf(readFileSync(file, "utf8"));
}

/** The whole file as a string. */
export function buildNotices() {
  const out = [];
  out.push("# Third-party notices", "");
  out.push("Everything below is bundled into, or served with, the panel page. Each entry names the package or file, the version,");
  out.push("the SPDX licence and where it came from, followed by the licence text exactly as shipped. The pins, hashes and the");
  out.push("checks behind them are in `VENDORED.md`, `assets/fonts/VENDORED.md` and `check-lock.mjs`. Generated by");
  out.push("`node tools/notices.mjs`; do not edit by hand.", "");

  out.push("## npm packages", "");
  for (const [name, want] of Object.entries(EXPECTED)) {
    if (!want.ships) continue;
    out.push(`### ${name} ${want.version}`, "");
    out.push(`- licence: ${want.license}`);
    out.push(`- source: https://registry.npmjs.org/${name} (tarball sha512 pinned in \`check-lock.mjs\`)`);
    out.push(name === "lucide-static" ? "- used for: the icon sprite (`assets/icons.svg`, built by `tools/icons.mjs`); only SVG paths of the listed icons are copied, no code" : "- used for: code bundled into the page by esbuild", "");
    out.push("```", packageLicense(name).trimEnd(), "```", "");
  }

  out.push("## Fonts (SIL Open Font License 1.1)", "");
  out.push("Subset to Latin, Latin-1, Latin Extended-A, punctuation, currency and arrows with pyftsubset; the origin, commit and hashes of each file are in `assets/fonts/VENDORED.md`.", "");
  const seen = new Set();
  for (const face of FACES) {
    if (seen.has(face.licenseFile)) continue;
    seen.add(face.licenseFile);
    const families = [...new Set(FACES.filter((f) => f.licenseFile === face.licenseFile).map((f) => f.family))].join(", ");
    out.push(`### ${families}`, "");
    out.push("```", lf(readFileSync(path.join(LICENSES_DIR, face.licenseFile), "utf8")).trimEnd(), "```", "");
  }

  out.push("## Build tools (not distributed)", "");
  out.push("esbuild (MIT), fonttools (MIT), brotli (MIT) and opentype-sanitizer (BSD-style) produce the page and the fonts; none of their code or data is in the page.", "");
  return out.join("\n");
}

function main() {
  const text = buildNotices();
  if (process.argv.includes("--check")) {
    const disk = existsSync(NOTICES) ? lf(readFileSync(NOTICES, "utf8")) : "";
    if (disk !== lf(text)) { console.error("THIRD_PARTY_NOTICES.md is not what tools/notices.mjs writes; run it"); process.exit(1); }
    console.log("ok: THIRD_PARTY_NOTICES.md is current");
    return;
  }
  writeFileSync(NOTICES, text);
  console.log(`wrote ${path.relative(process.cwd(), NOTICES)} (${text.length} bytes)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
